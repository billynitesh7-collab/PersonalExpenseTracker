CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transactions (
    id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(7) NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    amount NUMERIC NOT NULL CHECK (amount > 0),
    category VARCHAR(50) NOT NULL CHECK (length(trim(category)) > 0),
    date DATE NOT NULL,
    description VARCHAR(200) NOT NULL CHECK (length(trim(description)) > 0),
    display_order BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_transactions_user_date ON transactions(user_id, date);
CREATE INDEX ix_transactions_date ON transactions(date);
CREATE INDEX ix_transactions_type_date ON transactions(type, date);
CREATE INDEX ix_transactions_category_date ON transactions(category, date);

CREATE TABLE budgets (
    id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE CASCADE,
    month VARCHAR(7) NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    amount NUMERIC NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, month)
);
CREATE UNIQUE INDEX uq_budgets_unowned_month ON budgets(month) WHERE user_id IS NULL;
